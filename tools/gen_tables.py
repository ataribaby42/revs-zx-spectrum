"""Generate lookup tables for the Spectrum renderer and maths routines.

src/xconv.asm         yaw -> screen x conversion (3 pages):
                      XH lo, XH hi: floor(h * SCALE) for the signed high byte h
                      XL: floor(l * SCALE / 256) for the fraction byte l
                      (SCALE = pixels per yaw unit, see mcscale.py)
src/scale.asm         constants that depend on the scale
src/masks.asm         pixel masks (page): $00-$07 right-from masks ($FF >> n),
                      $08-$0F bit masks (128 >> n), $10-$17 left-to masks
                      ($FF << (7 - n))
src/maskx.asm         Compose boundary masks (page), indexed by the boundary x:
                      $FF >> (x & 7); x = 255 gives 0 (an edge clamped at the
                      right screen border: the span ends off the screen)
src/qsq.asm           quarter squares floor(i * i / 4), i = 0..511
(written by tools/gen_src.py, not by the build)
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from mcscale import MC_SCALE, YAW_SCALE as SCALE, mc_to_x  # noqa: E402
import srcdata  # noqa: E402


def main():
    xh_lo = bytearray(256)
    xh_hi = bytearray(256)
    xl = bytearray(256)
    for h in range(256):
        s = h - 256 if h >= 128 else h
        v = int(s * SCALE // 1) & 0xFFFF
        xh_lo[h] = v & 255
        xh_hi[h] = v >> 8
    for l in range(256):
        xl[l] = int(l * SCALE / 256)
    srcdata.write_db('xconv.asm', ['Generated by tools/gen_tables.py - yaw -> screen x conversion (3 pages):',
                                   'XH lo, XH hi: floor(h * SCALE), XL: floor(l * SCALE / 256)'],
                     xh_lo + xh_hi + xl)
    masks = bytearray(256)
    for n in range(8):
        masks[n] = 0xFF >> n
        masks[8 + n] = 0x80 >> n
        masks[16 + n] = (0xFF << (7 - n)) & 0xFF
    srcdata.write_db('masks.asm', ['Generated by tools/gen_tables.py - pixel masks (page): $FF >> n,',
                                   '128 >> n, $FF << (7 - n)'], masks)
    maskx = bytearray(0xFF >> (x & 7) for x in range(256))
    maskx[255] = 0
    srcdata.write_db('maskx.asm', ['Generated by tools/gen_tables.py - Compose boundary masks (page):',
                                   '$FF >> (x & 7), x = 255: 0'], maskx)
    # quarter squares floor(i*i/4), i = 0..511: lo bytes (2 pages), hi bytes (2 pages)
    q = [i * i // 4 for i in range(512)]
    # grass checks: C64 multicolour pixels 28-31 and 128-131 of track line 10
    left = (math.ceil(mc_to_x(28)), math.floor(mc_to_x(32)) - 1)
    right = (math.ceil(mc_to_x(128)), min(255, math.floor(mc_to_x(132)) - 1))
    lines = ['; Generated by tools/gen_tables.py - horizontal scale %.3f pixels per C64 pixel' % MC_SCALE,
             'MC_SCALE_X1000  EQU %d' % round(MC_SCALE * 1000),
             'SURF_LEFT       EQU %d * 256 + %d' % left,
             'SURF_RIGHT      EQU %d * 256 + %d' % right]
    srcdata.write('scale.asm', lines)
    srcdata.write_db('qsq.asm', ['Generated by tools/gen_tables.py - quarter squares floor(i * i / 4),',
                                 'i = 0..511: low bytes (2 pages), high bytes (2 pages)'],
                     [v & 255 for v in q] + [v >> 8 for v in q])


if __name__ == '__main__':
    main()

"""Generate src/objdata.asm: the object definitions (cars, signs,
markers) of the original game.

The part tables (objectTop, objectBottom, objectLeft, objectRight,
objectColour, objectIndex, scaffoldIndex) are copied from the C64 image (they
sit at the BBC addresses there). The C64 stores the scaffold measurements as
branch offsets into an unrolled scaling routine, so the measurements are taken
in the BBC encoding (%1abbbccc = a/2 + 1/2^(b-2) + 1/2^(c-2), %00000ccc =
1/2^(c-2)) from the annotated BBC source (its object scaffold table in
assets/bbc/object-scaffold.asm); every entry is checked against the value
in its comment.

Also emitted: h13Tab, the horizontal scale of the scaffold for s = 0..127.
The C64 draws an edge at xPixelCoord + scaffold / 2 multicolour pixels, so a
scaffold unit is MC_SCALE / 2 Spectrum pixels (see mcscale.py).

src/objterms.asm holds scafTermTab, the measurements decoded into
pairs of scaleTerms entries for the Z80 (scaffoldTab, the BBC encoding, is
kept in objdata.asm for the tests only).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from c64_image import main_image  # noqa: E402
from mcscale import MC_SCALE  # noqa: E402
import srcdata  # noqa: E402

PARTS = 41


def bbc_scaffold():
    """Scaffold measurements: encoded bytes and their values in 1/32."""
    src = (ROOT / 'assets/bbc/object-scaffold.asm').read_text()   # (BBC source excerpt)
    start = src.index('\n.objectScaffold\n')
    end = len(src)
    values = [int(v) for v in re.findall(r'=\s*(\d+)/32', src[start:end])]
    codes = [int(v, 2) for v in re.findall(r'EQUB %([01]{8})', src[start:end])]
    assert len(values) == len(codes)
    for c, v in zip(codes, values):
        if c & 0x80:
            total = 16 * ((c >> 6) & 1) + (32 >> (((c >> 3) & 7) - 2)) + (32 >> ((c & 7) - 2))
        else:
            total = 32 >> (c - 2)
        assert total == v, (bin(c), v, total)
    return codes, values


def main():
    m = main_image()
    tables = {
        'objTopTab': m[0x3550:0x3550 + PARTS], 'objBottomTab': m[0x35d0:0x35d0 + PARTS],
        'objLeftTab': m[0x3650:0x3650 + PARTS], 'objRightTab': m[0x36d0:0x36d0 + PARTS],
        'objColourTab': m[0x3750:0x3750 + PARTS],
        'objIndexTab': m[0x3cd0:0x3cd0 + 13], 'scafIndexTab': m[0x3cdd:0x3cdd + 14],
    }
    codes, values = bbc_scaffold()
    assert len(codes) == tables['scafIndexTab'][13] == 70, len(codes)
    out = ['; Generated by tools/gen_objects.py - object definitions', '']
    # h13Tab and scaleTerms share a page: ScaleObject keeps H on it
    out.append(f'h13Tab:                                 ; round(s * {MC_SCALE} / 2), page aligned')
    h13 = [min(255, int(s * MC_SCALE / 2 + 0.5)) for s in range(128)]
    for i in range(0, 128, 16):
        out.append('        db ' + ', '.join(str(v) for v in h13[i:i + 16]))
    out.append('scaleTerms:     ds 9                    ; ScaleObject: scaleUp >> 0..5, 0,')
    out.append('                                        ; scaleUp >> 1 + scaleUp >> 2, >> 1 + >> 3')
    out.append('        ASSERT h13Tab % 256 == 0 && scaleTerms / 256 == h13Tab / 256')
    out.append('scafIndexTab:')
    out.append('        db ' + ', '.join(f'${b:02X}' for b in tables['scafIndexTab']))
    # parts interleaved for DrawObjectParts: colour, top, bottom, left, right
    out.append('objPartOffTab:                          ; 5 * first part of each object type')
    out.append('        db ' + ', '.join(str(5 * b) for b in tables['objIndexTab']))
    out.append('objPartTab:                             ; colour, top, bottom, left, right')
    for k in range(PARTS):
        out.append('        db ' + ', '.join(f'${tables[t][k]:02X}' for t in
                                           ('objColourTab', 'objTopTab', 'objBottomTab',
                                            'objLeftTab', 'objRightTab')))
    out.append('        IF 0                            ; original tables (tests)')
    for name, data in tables.items():
        if name == 'scafIndexTab':
            continue
        out.append(f'{name}:')
        for i in range(0, len(data), 16):
            out.append('        db ' + ', '.join(f'${b:02X}' for b in data[i:i + 16]))
    out.append('scaffoldTab:                            ; the BBC encoding, see scafTermTab')
    for i in range(0, len(codes), 16):
        out.append('        db ' + ', '.join(f'${v:02X}' for v in codes[i:i + 16]))
    out.append('        ENDIF')
    out.append('; (values in 1/32: ' + ' '.join(str(v) for v in values) + ')')
    srcdata.write('objdata.asm', out)

    # scafTermTab: each measurement as two scaleTerms entries to add
    # (%1abbbccc = a/2 + 1/2^(b-2) + 1/2^(c-2): the a/2 term is folded into
    # the entries 7 (b = 4) and 8 (b = 5); %00000ccc adds the zero entry 6)
    terms = []
    for c in codes:
        if c & 0x80:
            b, cc = (c >> 3) & 7, c & 7
            assert 2 <= b <= 7 and 2 <= cc <= 7
            if c & 0x40:
                assert b in (4, 5), hex(c)
                t2 = 7 + (b - 4)
            else:
                t2 = b - 2
            terms.append((cc - 2, t2))
        else:
            assert 2 <= c <= 7
            terms.append((c - 2, 6))
    out = ['; Generated by tools/gen_objects.py - scaffold measurements as pairs of',
           '; scaleTerms entries (low address bytes), see ScaleObject', 'scafTermTab:']
    for i in range(0, len(terms), 8):
        out.append('        db ' + ', '.join(f'scaleTerms % 256 + {a}, scaleTerms % 256 + {b}'
                                           for a, b in terms[i:i + 8]))
    srcdata.write('objterms.asm', out)


if __name__ == '__main__':
    main()

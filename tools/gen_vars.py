"""Generate src/zp.asm: the BBC zero page ($00-$8F) as offsets into the
Z80 block ZPAGE, keeping the original layout and its aliases (several names
share one byte in the original). Written by tools/gen_src.py, not by the
build."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import srcdata  # noqa: E402

RENAME = {'H': 'Hv', 'I': 'Iv', 'L': 'Lv'}   # clash with register names
SKIP = {'P', 'Q', 'R', 'S'}                  # also register-like / unused here


def main():
    out = ['; Generated by tools/gen_vars.py - BBC zero page layout', '']
    for line in (ROOT / 'notes/bbc-symbols.txt').read_text().split('\n'):
        if not line.strip():
            continue
        a, name = line.split()
        addr = int(a[1:], 16)
        if addr >= 0x90 or name in SKIP:
            continue
        name = RENAME.get(name, name)
        out.append(f'{name:24s} EQU ZPAGE + ${addr:02X}')
    srcdata.write('zp.asm', out)


if __name__ == '__main__':
    main()

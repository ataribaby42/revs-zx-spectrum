"""Generate src/text.asm: driver names (from the C64 image) and the
dashboard overlays, and src/gfx/gears.bin (gear glyphs from
assets/cockpit/gears.png).

Driver names: 20 x 12 characters, driver n at driverNames1 + (n div 4) * $100
+ (n mod 4) * 12 in the C64 image (as on the BBC). Driver 19 is the player.

Rev counter hand: end point offsets (dx, dy) from the dial centre for the
152 dial positions of the BBC DrawRevCounter.

Gear glyphs: seven 10 x 6 fields (R, N, 1-5) shown at screen (219, 179),
i.e. byte columns 27-28 from bit 3; stored per glyph as 6 rows of two bytes
(white pixels set), plus the two byte masks of the field.
"""
import math
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from c64_image import main_image  # noqa: E402
import srcdata  # noqa: E402

GEAR_X, GEAR_Y = 219, 179
NEEDLE_LEN = 16
WHEEL_IN, WHEEL_OUT = 37, 42            # steering wheel rim radii (centre 128, 175)


def main():
    m = main_image()
    out = ['; Generated by tools/gen_text.py', '']
    out.append('driverNames:                            ; 20 x 12 characters')
    for n in range(20):
        a = 0x4050 + (n // 4) * 0x100 + (n % 4) * 12
        name = bytes(m[a:a + 12]).decode('ascii')
        if n == 19:
            name = 'YOU'.ljust(12)
        out.append(f'        db "{name}"')
    img = Image.open(ROOT / 'assets/cockpit/gears.png').convert('RGBA')
    px = img.load()
    shift = GEAR_X & 7
    out.append('')
    out.append(f'GEAR_ADDR_COL   EQU {GEAR_X >> 3}')
    out.append(f'GEAR_ROW        EQU {GEAR_Y}')
    mask = ((1 << 10) - 1) << (16 - 10 - shift)
    out.append(f'GEAR_MASK0      EQU ${mask >> 8:02X}')
    out.append(f'GEAR_MASK1      EQU ${mask & 255:02X}')
    out.append('gearGlyphs:                             ; R N 1 2 3 4 5, 6 rows x 2 bytes')
    out.append('        INCBIN "gfx/gears.bin"')
    glyphs = []
    for g in range(7):
        for y in range(6):
            v = 0
            for x in range(10):
                r, gg, b, a = px[g * 10 + x, y]
                if a >= 128 and r >= 128:          # white pixel = ink off (paper)
                    v |= 1 << (9 - x)
            v <<= (16 - 10 - shift)
            glyphs += [v >> 8, v & 255]
    srcdata.write_bin('gfx/gears.bin', glyphs)
    # rev counter hand: end point offsets for the 152 BBC dial positions
    # (0 = 12 o'clock, clockwise)
    out.append('needleTab:                              ; dx, dy per dial position')
    for u0 in range(0, 152, 8):
        vals = []
        for u in range(u0, min(u0 + 8, 152)):
            ang = u * 2 * math.pi / 152
            vals += [round(NEEDLE_LEN * math.sin(ang)) & 255, round(-NEEDLE_LEN * math.cos(ang)) & 255]
        out.append('        db ' + ', '.join(f'${v:02X}' for v in vals))
    srcdata.write('text.asm', out)


if __name__ == '__main__':
    main()
